const { contextBridge, ipcRenderer, webUtils } = require("electron");

const on = ch => fn => ipcRenderer.on(ch, (_, d) => fn(d));
contextBridge.exposeInMainWorld("bridge", {
  onMedia: on("media"),
  onClaude: on("claude"),
  onToggle: on("toggle"),
  onLevels: on("levels"),
  onVolume: on("volume"),
  onVolumeHud: on("volumeHud"),
  onSearch: on("search"),
  onSearchDone: on("searchDone"),
  search: q => ipcRenderer.invoke("search", q),
  searchRun: id => ipcRenderer.send("searchRun", id),
  quickGet: () => ipcRenderer.invoke("quickGet"),
  quickSet: (kind, value) => ipcRenderer.invoke("quickSet", kind, value),
  onSpotifyExtras: on("spotifyExtras"),
  onNotification: on("notification"),
  onCalendar: on("calendar"),
  onTimer: on("timer"),
  onTimerLabel: on("timerLabel"),
  onStopwatch: on("stopwatch"),
  onSpotifyIcon: on("spotifyIcon"),
  onSystem: on("system"),
  onPower: on("power"),
  onLyrics: on("lyrics"),
  onDnd: on("dnd"),
  toggleDnd: () => ipcRenderer.send("toggleDnd"),
  phoneStart: () => ipcRenderer.invoke("phoneStart"),
  phoneStop: () => ipcRenderer.send("phoneStop"),
  linksGet: () => ipcRenderer.invoke("linksGet"),
  linksSave: list => ipcRenderer.invoke("linksSave", list),
  openLink: url => ipcRenderer.send("openLink", url),
  copyText: t => ipcRenderer.send("copyText", t),
  timerStart: min => ipcRenderer.send("timerStart", min),
  stopwatchToggle: () => ipcRenderer.send("stopwatchToggle"),
  openSettings: () => ipcRenderer.send("openSettings"),
  sysStats: () => ipcRenderer.invoke("sysStats"),
  onClipboard: on("clipboard"),
  onWeather: on("weather"),
  onTheme: on("theme"),
  onDownloads: on("downloads"),
  onDownloadDone: on("downloadDone"),
  onScreenshot: on("screenshot"),
  onDevices: on("devices"),
  onDeviceLow: on("deviceLow"),
  onAgentUpdate: on("agentUpdate"),
  onUpdateReady: on("updateReady"),
  onDndSummary: on("dndSummary"),
  copyClip: i => ipcRenderer.send("copyClip", i),
  onNotes: on("notes"),
  saveNotes: t => ipcRenderer.send("saveNotes", t),
  pinClip: i => ipcRenderer.send("pinClip", i),
  clearClips: () => ipcRenderer.send("clearClips"),
  onShelf: on("shelf"),
  // dropped File objects -> real paths (File.path was removed from Electron)
  shelfAddFiles: files => ipcRenderer.send("shelfAdd", [...files].map(f => webUtils.getPathForFile(f)).filter(Boolean)),
  shelfPick: () => ipcRenderer.send("shelfPick"),
  shelfRemove: p => ipcRenderer.send("shelfRemove", p),
  shelfOpen: p => ipcRenderer.send("shelfOpen", p),
  shelfDrag: p => ipcRenderer.send("shelfDrag", p),
  onPermission: on("permission"),
  onPermissionGone: on("permissionGone"),
  answerPermission: (id, decision) => ipcRenderer.send("permissionAnswer", id, decision),
  control: cmd => ipcRenderer.send("control", cmd),
  hover: over => ipcRenderer.send("hover", over),
  notchBox: box => ipcRenderer.send("notchBox", box),
  seek: sec => ipcRenderer.send("seek", sec),
  volume: delta => ipcRenderer.send("volume", delta),
  like: () => ipcRenderer.send("like"),
  openProject: cwd => ipcRenderer.send("openProject", cwd),
  openNotification: id => ipcRenderer.send("openNotification", id),
  joinMeeting: url => ipcRenderer.send("joinMeeting", url),
  installUpdate: () => ipcRenderer.send("installUpdate"),
});
